  const LANGS = ['en', 'pl', 'de', 'fr', 'es', 'it', 'nl', 'da', 'no', 'ru']
  const NAMES = { en: 'English', pl: 'Polski', de: 'Deutsch', fr: 'Français', es: 'Español', it: 'Italiano', nl: 'Nederlands', da: 'Dansk', no: 'Norsk', ru: 'Русский' }

  /** A system locale ("pl-PL", "nb-NO", "en-GB") -> one of LANGS, English when none fits. */
  function pick(locale) {
    const l = String(locale || '').toLowerCase().split(/[-_]/)[0]
    if (l === 'nb' || l === 'nn') return 'no'
    return LANGS.includes(l) ? l : 'en'
  }

  /** text in `lang`, English when a key is missing there; {name} filled from `vars` */
  function t(lang, key, vars) {
    const s = (T[lang] && T[lang][key]) || T.en[key] || key
    return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined ? m : String(vars[k]))) : s
  }

  const api = { T, LANGS, NAMES, pick, t }
